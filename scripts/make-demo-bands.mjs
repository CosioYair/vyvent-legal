/* Author the six DEMONSTRATION interlude bands for wedding_romantic_v1.
 *
 * Run once, output committed: `node scripts/make-demo-bands.mjs`.
 *
 * These are DEMO assets. They exist so `?demo=wedding_romantic_v1` can show
 * what photos distributed through an invitation actually look like, and they
 * live under assets/demo/ precisely so nothing can mistake them for content a
 * real organizer chose. A real invitation references its own uploads or its own
 * event photos; it can never reference anything in this directory.
 *
 * They share one frame (landscape band, warm ground, soft vignette) and differ
 * only by motif, which is what a run of photographs through one invitation
 * should feel like. Palette is template.css exactly.
 *
 * A script rather than six hand-copied files because the frame is identical in
 * all six: editing the shared part in one place is the difference between six
 * consistent bands and six that drift.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
